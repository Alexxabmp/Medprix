import { buildDocumentPdf, downloadPdf } from "@/lib/document-pdf";
import { PHARMACY_PROFILE, longDate } from "@/lib/procurement-documents";
import type { WholesaleCollection, WholesaleReceivableDetail } from "@/lib/wholesale-api";

/** Payment terms in words, so a reader sees at once whether there are installments. */
export const planLabel = (plan: string | null | undefined) =>
  plan === "Net60" ? "Net 60 · 2 installments" : plan === "Net30" ? "Net 30 · 1 payment" : "Credit terms";

const php = (value: string | number | null | undefined) => {
  const n = Number(String(value ?? "0").replace(/[₱,\s]/g, ""));
  return `PHP ${(Number.isFinite(n) ? n : 0).toLocaleString("en-PH", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
};
const manilaDay = (instant: string) => new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Manila" }).format(new Date(instant));

/** Collection receipt for one client payment (CR-YYYY-NNNN). A reversed payment is stamped REVERSED. */
export function collectionReceiptPdf(detail: WholesaleReceivableDetail, payment: WholesaleCollection) {
  const counted = detail.payments.filter(p => !p.reversalId && p.collectedAt <= payment.collectedAt);
  const paidToDate = counted.reduce((sum, p) => sum + Math.round(Number(p.amount) * 100), 0) / 100;
  const due = new Map((detail.installments ?? []).map(i => [i.sequenceNumber, i]));
  const count = detail.installments?.length ?? 0;
  const bytes = buildDocumentPdf({
    title: payment.reversalId ? "Collection receipt (REVERSED)" : "Collection receipt",
    number: payment.receiptNumber ?? "No receipt number",
    date: longDate(manilaDay(payment.collectedAt)),
    pharmacy: PHARMACY_PROFILE,
    boxes: [
      { heading: "Received from", lines: [detail.clientName] },
      { heading: "For order", lines: [`${detail.orderNumber} · ${planLabel(detail.paymentPlan)}`, `Delivered ${longDate(manilaDay(detail.deliveredAt))}`] },
      { heading: "Amount received", lines: [php(payment.amount), payment.method + (payment.reference ? ` · Ref. ${payment.reference}` : "")] },
      { heading: "As of this receipt", lines: [`Order total: ${php(detail.total)}`, `Paid to date: ${php(paidToDate)}`, `Balance left: ${php(Number(detail.total) - paidToDate)}`] },
    ],
    table: {
      columns: [{ label: "Applied to", width: 34 }, { label: "Due", width: 22 }, { label: "Installment", width: 22, align: "right" }, { label: "This payment", width: 22, align: "right" }],
      rows: payment.allocations.map(a => [
        `Installment ${a.sequenceNumber} of ${count}`,
        longDate(due.get(a.sequenceNumber)?.dueDate ?? null),
        php(due.get(a.sequenceNumber)?.amount ?? 0),
        php(a.amount),
      ]),
    },
    paragraphs: [
      payment.officialReceiptNumber
        ? `Pharmacy official receipt / invoice no.: ${payment.officialReceiptNumber}`
        : "Pharmacy official receipt / invoice no.: ____________ (write it here if one is issued)",
      ...(payment.reversalId ? [`REVERSED on ${longDate(manilaDay(payment.reversedAt ?? payment.collectedAt))}: ${payment.reversalReason ?? ""}. This payment no longer counts toward the balance.`] : []),
      "This acknowledges payment received.",
    ],
    signatures: [{ name: payment.collectorName, role: "Received by" }, { name: "", role: "Client signature" }],
    footer: `Generated by Medprix - ${payment.receiptNumber ?? "collection receipt"}`,
  });
  downloadPdf(bytes, `${payment.receiptNumber ?? "collection-receipt"}.pdf`);
}

export type WholesaleStatement = {
  client: { id: string; name: string; contactPerson: string | null; contactNumber: string | null; email: string | null; address: string | null };
  asOf: string;
  totals: { billed: string; paid: string; balance: string; overdue: string };
  aging: { current: string; days1to30: string; days31to60: string; days61to90: string; over90: string };
  orders: { orderNumber: string; paymentPlan: string; total: string; paid: string; balance: string;
    installments: { sequenceNumber: number; dueDate: string; amount: string; paid: string; balance: string; daysLate: number }[] }[];
  payments: { orderNumber: string; receiptNumber: string | null; collectedAt: string; amount: string; method: string; reference: string | null; reversed: boolean }[];
};

/** Statement of account for one client: totals, how late, open installments, recent payments. */
export function statementPdf(s: WholesaleStatement) {
  const rows = s.orders.flatMap(o => o.installments.filter(i => Number(i.balance) > 0).map(i => [
    o.orderNumber, `${planLabel(o.paymentPlan)}${o.installments.length > 1 ? ` (${i.sequenceNumber} of ${o.installments.length})` : ""}`,
    longDate(i.dueDate), php(i.amount), php(i.paid), php(i.balance), i.daysLate ? `${i.daysLate} days late` : "Not yet due",
  ]));
  const overdue = Number(s.totals.overdue) > 0;
  const bytes = buildDocumentPdf({
    title: "Account statement",
    number: s.client.name,
    date: `As of ${longDate(s.asOf)}`,
    pharmacy: PHARMACY_PROFILE,
    boxes: [
      { heading: "Client", lines: [s.client.name, ...[s.client.contactPerson, s.client.contactNumber].filter(Boolean) as string[], ...(s.client.address ? [s.client.address] : [])] },
      { heading: "Summary", lines: [`Billed (open orders): ${php(s.totals.billed)}`, `Paid: ${php(s.totals.paid)}`, `Balance: ${php(s.totals.balance)}`, `Overdue: ${php(s.totals.overdue)}`] },
    ],
    table: {
      columns: [{ label: "Not yet due", width: 20, align: "right" }, { label: "1-30 days", width: 20, align: "right" }, { label: "31-60 days", width: 20, align: "right" }, { label: "61-90 days", width: 20, align: "right" }, { label: "Over 90 days", width: 20, align: "right" }],
      rows: [[php(s.aging.current), php(s.aging.days1to30), php(s.aging.days31to60), php(s.aging.days61to90), php(s.aging.over90)]],
    },
    extraTables: [
      { heading: "Open orders and installments", columns: [{ label: "Order", width: 9 }, { label: "Terms", width: 21 }, { label: "Due", width: 17 }, { label: "Amount", width: 14, align: "right" }, { label: "Paid", width: 13, align: "right" }, { label: "Left", width: 13, align: "right" }, { label: "Status", width: 13 }],
        rows: rows.length ? rows : [["-", "No open balances", "", "", "", "", ""]] },
      { heading: "Payments in the last 90 days", columns: [{ label: "Receipt", width: 18 }, { label: "Date", width: 22 }, { label: "Order", width: 10 }, { label: "Method / reference", width: 32 }, { label: "Amount", width: 18, align: "right" }],
        rows: s.payments.length ? s.payments.map(p => [p.receiptNumber ?? "-", longDate(manilaDay(p.collectedAt)), p.orderNumber, p.method + (p.reference ? ` · ${p.reference}` : "") + (p.reversed ? " (reversed)" : ""), p.reversed ? `(${php(p.amount)})` : php(p.amount)])
          : [["-", "", "", "No payments recorded", ""]] },
    ],
    callout: overdue
      ? `Please settle the overdue amount of ${php(s.totals.overdue)}. Pay by cash at the pharmacy or by bank transfer and send us the reference number. New credit orders are on hold until the overdue balance is paid or an administrator approves them.`
      : undefined,
    paragraphs: ["Amounts match the pharmacy's receivables and Finance dashboard on the date above."],
    footer: `Generated by Medprix - Statement of account ${s.client.name} ${s.asOf}`,
  });
  downloadPdf(bytes, `statement-${s.client.name.replace(/[^A-Za-z0-9-]+/g, "-")}-${s.asOf}.pdf`);
}
