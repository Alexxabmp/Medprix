import { SUPPLIER_TERMS_LABEL, SUPPLIER_PAYMENT_MODE_LABEL, DELIVERY_REJECTION_REASON_LABEL, describeSupplierTerms, type SupplierPaymentMode } from "@workspace/api-zod";
import { buildDocumentPdf, downloadPdf, openPdf, type PdfDocument } from "./document-pdf";
import type { OrderDetail, Delivery, Invoice, PaymentAdvice } from "./procurement-api";

/**
 * The pharmacy's details printed on every procurement document.
 * Fill these in once (address, TIN, contact number) before using the documents with suppliers.
 */
export const PHARMACY_PROFILE = {
  name: "Med Prix Drug Distributor & Pharmacy",
  lines: ["[Pharmacy address]", "TIN [000-000-000-000] - [Contact number]"],
};

const amount = (value: string | number | null | undefined) => {
  const n = Number(String(value ?? "0").replace(/[₱,\s]/g, ""));
  return `PHP ${(Number.isFinite(n) ? n : 0).toLocaleString("en-PH", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
};
export const longDate = (value: string | null | undefined) => {
  if (!value) return "-";
  const day = String(value).slice(0, 10);
  const d = new Date(`${day}T00:00:00Z`);
  return Number.isNaN(d.getTime()) ? String(value) : d.toLocaleDateString("en-PH", { year: "numeric", month: "long", day: "numeric", timeZone: "UTC" });
};
const manilaDay = (value: string | null | undefined) =>
  value ? new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Manila" }).format(new Date(value)) : null;
const supplierLines = (s: { name: string; contactPerson: string | null; contactNumber: string | null; email: string | null; address: string | null }) =>
  [s.name, s.contactPerson ? `Attn: ${s.contactPerson}` : "", s.address ?? "", [s.contactNumber, s.email].filter(Boolean).join(" - ")].filter(Boolean);

export function purchaseOrderPdf(detail: OrderDetail) {
  const { order, lines } = detail;
  const doc: PdfDocument = {
    title: "Purchase order", number: order.poNumber, date: longDate(manilaDay(order.orderDate)),
    pharmacy: PHARMACY_PROFILE,
    boxes: [
      { heading: "Supplier", lines: supplierLines(order.supplier) },
      { heading: "Order terms", lines: [
        `Payment terms: ${SUPPLIER_TERMS_LABEL[order.supplier.paymentTerms]}. ${describeSupplierTerms(order.supplier.paymentTerms, order.supplier.termsBasis)}`,
        `Requested delivery: ${order.expectedDeliveryDate ? longDate(order.expectedDeliveryDate) : "As soon as available"}`,
        `Deliver to: ${PHARMACY_PROFILE.lines[0]}`,
        "Please write the lot number and expiry of each item on the delivery receipt.",
      ] },
    ],
    table: {
      columns: [{ label: "#", width: 4 }, { label: "Medicine", width: 34 }, { label: "SKU", width: 14 }, { label: "Quantity", width: 12, align: "right" },
        { label: "Unit cost", width: 16, align: "right" }, { label: "Line total", width: 18, align: "right" }],
      rows: lines.map((l, i) => [String(i + 1), l.product, l.sku, l.quantityOrdered.toLocaleString("en-PH"), amount(l.unitCost), amount(l.quantityOrdered * Number(l.unitCost))]),
      totals: [["Order total", amount(order.totalOrderAmount)]],
    },
    paragraphs: [
      "Unit costs as agreed with the supplier. Please confirm availability and the delivery date. Partial deliveries are accepted; list what is still to follow on the delivery receipt.",
      ...(order.notes ? [`Notes: ${order.notes}`] : []),
    ],
    signatures: [
      { name: order.createdBy ?? "", role: "Prepared by" },
      { name: order.approvedBy ?? "", role: order.selfApproved ? "Approved by (own order)" : "Approved by" },
    ],
    footer: `Generated by Medprix - ${order.poNumber}`,
  };
  return buildDocumentPdf(doc);
}

export function receivingReportPdf(detail: OrderDetail, delivery: Delivery) {
  const { order } = detail;
  const index = detail.deliveries.findIndex(d => d.id === delivery.id) + 1;
  return buildDocumentPdf({
    title: "Receiving report", number: `${order.poNumber}-RR${index}`, date: longDate(delivery.deliveryDate),
    pharmacy: PHARMACY_PROFILE,
    boxes: [
      { heading: "Supplier", lines: supplierLines(order.supplier) },
      { heading: "Delivery", lines: [
        `Purchase order: ${order.poNumber}`,
        `Supplier's delivery receipt: ${delivery.receiptNumber ?? "Not given"}`,
        `Delivery date: ${longDate(delivery.deliveryDate)}`,
        `Received by: ${delivery.receivedBy ?? "-"}`,
      ] },
    ],
    table: {
      columns: [{ label: "Medicine", width: 34 }, { label: "Lot no.", width: 18 }, { label: "Expiry", width: 18 }, { label: "Good qty", width: 14, align: "right" }],
      rows: delivery.items.map(i => [`${i.product} (${i.sku})`, i.batchNumber, `${longDate(i.expirationDate)}${i.shortExpiry ? " (short)" : ""}`, String(i.quantity)]),
      totals: [["Units added to stock", String(delivery.items.reduce((s, i) => s + i.quantity, 0))]],
    },
    extraTables: delivery.rejections.length ? [{
      heading: "Rejected (not added to stock; still due from the supplier)",
      columns: [{ label: "Medicine", width: 34 }, { label: "Qty", width: 10, align: "right" }, { label: "Reason", width: 22 }, { label: "Notes", width: 34 }],
      rows: delivery.rejections.map(r => [`${r.product} (${r.sku})`, String(r.quantity), DELIVERY_REJECTION_REASON_LABEL[r.reason], r.notes ?? ""]),
    }] : [],
    paragraphs: [
      `Still due on this order after this delivery: ${detail.lines.filter(l => l.quantityRemaining > 0).map(l => `${l.quantityRemaining} ${l.product}`).join(", ") || "nothing"}.`,
      ...(delivery.notes ? [`Notes: ${delivery.notes}`] : []),
    ],
    signatures: [{ name: delivery.receivedBy ?? "", role: "Received and checked by" }, { name: order.supplier.contactPerson ?? "", role: "Delivered by (supplier)" }],
    footer: `Generated by Medprix - ${order.poNumber} receiving report ${index}`,
  });
}

export function invoiceRecordPdf(detail: OrderDetail, invoice: Invoice) {
  const { order } = detail;
  return buildDocumentPdf({
    title: "Supplier invoice record", number: invoice.invoiceNumber, date: longDate(invoice.invoiceDate),
    pharmacy: PHARMACY_PROFILE,
    boxes: [
      { heading: "Supplier", lines: supplierLines(order.supplier) },
      { heading: "Invoice", lines: [
        `Purchase order: ${order.poNumber}`,
        `Status: ${invoice.status === "Verified" ? "Verified against delivery" : "Pending verification (billed before delivery)"}`,
        `Terms: ${SUPPLIER_TERMS_LABEL[invoice.terms]}${invoice.termsOverrideReason ? ` (special: ${invoice.termsOverrideReason})` : ""}`,
        `Due date: ${longDate(invoice.dueDate)}`,
      ] },
    ],
    table: {
      columns: [{ label: "Payment date", width: 18 }, { label: "Advice no.", width: 18 }, { label: "Mode / reference", width: 30 }, { label: "Supplier OR", width: 16 }, { label: "Amount", width: 18, align: "right" }],
      rows: invoice.payments.map(p => [longDate(manilaDay(p.paymentDate)), p.adviceNumber ?? "-",
        `${p.mode ? SUPPLIER_PAYMENT_MODE_LABEL[p.mode] : "-"}${p.referenceNumber ? ` ${p.referenceNumber}` : ""}`, p.supplierOrNumber ?? "-", amount(p.amount)]),
      totals: [["Invoice amount", amount(invoice.amount)], ["Paid", amount(invoice.totalPaid)], ["Balance", amount(invoice.balance)]],
    },
    paragraphs: invoice.varianceReason ? [`Difference from received goods: ${invoice.varianceReason}`] : [],
    footer: `Generated by Medprix - ${invoice.invoiceNumber}`,
  });
}

export function paymentAdvicePdf(advice: PaymentAdvice) {
  const { payment, invoice, supplier } = advice;
  const mode = payment.mode ? SUPPLIER_PAYMENT_MODE_LABEL[payment.mode as SupplierPaymentMode] : "-";
  const number = payment.adviceNumber ?? payment.id.slice(0, 8).toUpperCase();
  return buildDocumentPdf({
    title: "Payment advice", number, date: longDate(manilaDay(payment.paymentDate)),
    pharmacy: PHARMACY_PROFILE,
    boxes: [
      { heading: "Paid to", lines: supplierLines(supplier) },
      { heading: "Payment", lines: [
        `Mode: ${mode}`, `Reference no.: ${payment.referenceNumber ?? (payment.mode === "Cash" ? "Cash" : "-")}`,
        `Payment date: ${longDate(manilaDay(payment.paymentDate))}`, `Amount: ${amount(payment.amount)}`,
      ] },
    ],
    table: {
      columns: [{ label: "Invoice no.", width: 13 }, { label: "Our PO", width: 14 }, { label: "Invoice date", width: 13 }, { label: "Invoice amount", width: 16, align: "right" },
        { label: "Paid before", width: 14, align: "right" }, { label: "This payment", width: 15, align: "right" }, { label: "Balance", width: 15, align: "right" }],
      rows: [[invoice.invoiceNumber, invoice.poNumber ?? "-", longDate(invoice.invoiceDate), amount(invoice.amount), amount(invoice.paidBefore), amount(payment.amount), amount(invoice.balanceAfter)]],
    },
    callout: `This is a notice of payment from ${PHARMACY_PROFILE.name}, not an official receipt. Please issue your Official Receipt for ${amount(payment.amount)} referencing invoice ${invoice.invoiceNumber}.${
      Number(invoice.balanceAfter) > 0 ? ` The remaining balance of ${amount(invoice.balanceAfter)} is due on ${longDate(invoice.dueDate)}.` : " This invoice is now fully paid."}${payment.isPrepayment ? " This is an advance payment; the invoice will be checked against the delivery." : ""}`,
    paragraphs: payment.supplierOrNumber ? [`Supplier OR no.: ${payment.supplierOrNumber}`] : [],
    signatures: [{ name: payment.recordedBy ?? "", role: `Recorded by${payment.recordedByRole ? ` - ${payment.recordedByRole === "FrontDesk" ? "Front desk" : payment.recordedByRole}` : ""}` }],
    footer: `Generated by Medprix - ${number}`,
  });
}

export const savePdf = (bytes: Uint8Array, name: string) => downloadPdf(bytes, `${name.replace(/[^A-Za-z0-9-]+/g, "-")}.pdf`);
export const printPdf = (bytes: Uint8Array) => openPdf(bytes);
